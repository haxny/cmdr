/**
 * Astro integration that lets the CSP allow the site's own inline scripts by hash instead of
 * `'unsafe-inline'`. It hashes every executable inline `<script>` in the built HTML and writes
 * them into an nginx snippet that sets `$csp_script_hashes`, which `nginx-security-headers.conf`
 * puts into the policy. One union across all pages, because `<ClientRouter />` runs the next
 * page's inline scripts inside the current page's policy.
 *
 * Astro's own `security.csp` can't do this job: it doesn't support `<ClientRouter />`, and it
 * emits a `<meta>` policy, which can't report violations.
 *
 * Runs at `astro:build:done`, after every integration that rewrites HTML, because a hash covers
 * the script's exact bytes. Data blocks (`application/ld+json`) aren't executed, so CSP doesn't
 * govern them and they get no hash.
 */

import type { AstroIntegration } from 'astro'
import { createHash } from 'node:crypto'
import { mkdir, readFile, readdir, writeFile } from 'node:fs/promises'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

/** An end tag may carry whitespace (`</script >`), which the browser still honors. */
const SCRIPT_ELEMENT = /<script(\s[^>]*)?>([\s\S]*?)<\/script\b[^>]*>/gi

/** Script types the browser executes, so CSP applies. An absent `type` is classic JS. */
const EXECUTABLE_TYPE = /^(?:module|text\/javascript|application\/javascript)$/i

/** The CSP source expressions (`'sha256-…'`) for the executable inline scripts in `html`. Pure. */
export function inlineScriptHashes(html: string): string[] {
  const hashes: string[] = []
  for (const [, attributes = '', body] of html.matchAll(SCRIPT_ELEMENT)) {
    if (/\ssrc\s*=/i.test(attributes)) continue
    const type = /\stype\s*=\s*["']?([^"'\s>]+)/i.exec(attributes)?.[1]
    if (type !== undefined && !EXECUTABLE_TYPE.test(type)) continue
    hashes.push(`'sha256-${createHash('sha256').update(body, 'utf8').digest('base64')}'`)
  }
  return hashes
}

/** The nginx snippet that sets `$csp_script_hashes`. Sorted, so an unchanged site builds an identical file. */
export function nginxSnippet(hashes: Iterable<string>): string {
  const sorted = [...new Set(hashes)].sort()
  return [
    '# Generated by apps/website/src/plugins/csp-hashes.ts at build time. Do not edit.',
    `set $csp_script_hashes "${sorted.join(' ')}";`,
    '',
  ].join('\n')
}

export function cspHashesIntegration({ snippetPath }: { snippetPath: string }): AstroIntegration {
  return {
    name: 'csp-hashes',
    hooks: {
      'astro:build:done': async ({ dir, logger }) => {
        const distDir = fileURLToPath(dir)
        const entries = await readdir(distDir, { withFileTypes: true, recursive: true })
        const hashes = new Set<string>()
        for (const entry of entries) {
          if (!entry.isFile() || !entry.name.endsWith('.html')) continue
          for (const hash of inlineScriptHashes(await readFile(join(entry.parentPath, entry.name), 'utf8'))) {
            hashes.add(hash)
          }
        }
        await mkdir(dirname(snippetPath), { recursive: true })
        await writeFile(snippetPath, nginxSnippet(hashes))
        logger.info(`hashed ${String(hashes.size)} distinct inline script(s) into ${snippetPath}`)
      },
    },
  }
}
