<script lang="ts">
    // What the rename review says about its own check and its last refusal, above the list.
    import Button from '#lib/ui/Button.svelte'
    import ProgressBar from '#lib/ui/ProgressBar.svelte'
    import { tString } from '#lib/intl/messages.svelte.js'
    import { formatInteger } from '#lib/intl/number-format.js'
    import { renameCheckProgress, renameNoticeWords, uncheckedRowCount } from './rename-review-status'
    import {
        checkRenameReviewAgain,
        stopRenameChecks,
        type BulkRenameReviewProposal,
        type RenameReviewNotice,
    } from './ask-cmdr-trigger.svelte'

    const { proposals, notice }: { proposals: BulkRenameReviewProposal[]; notice: RenameReviewNotice | null } = $props()

    const progress = $derived(renameCheckProgress(proposals))
    const progressLabel = $derived(
        progress
            ? tString('askCmdr.renameReview.checking', {
                  checkedText: formatInteger(progress.checked),
                  totalText: formatInteger(progress.total),
                  total: progress.total,
              })
            : '',
    )
    const uncheckedCount = $derived(uncheckedRowCount(proposals))
    const noticeWords = $derived(notice ? renameNoticeWords(notice) : null)
    /** Stop checking leaves with its own press, so focus moves on to what replaces it. Set only by
     *  that press: Check again turning up by itself mustn't take focus from a name being typed. */
    let stopPressed = $state(false)

    function onStopChecking(): void {
        stopPressed = true
        stopRenameChecks()
    }
</script>

{#if progress}
    <div class="check-progress" data-rename-check="running">
        <ProgressBar
            size="sm"
            value={progress.total > 0 ? progress.checked / progress.total : 0}
            ariaLabel={tString('askCmdr.renameReview.checkingLabel')}
            ariaValuetext={progressLabel}
        />
        <span class="check-count">{progressLabel}</span>
        <Button size="mini" onclick={onStopChecking}>
            {tString('askCmdr.renameReview.stopChecking')}
        </Button>
    </div>
{/if}
{#if uncheckedCount > 0}
    <div class="notice unchecked" role="status" data-rename-check="unfinished">
        <span class="unchecked-words">{tString('askCmdr.renameReview.checkUnfinished', { count: uncheckedCount })}</span>
        <Button size="mini" autoFocus={stopPressed} onclick={checkRenameReviewAgain}>
            {tString('askCmdr.renameReview.checkAgain')}
        </Button>
    </div>
{/if}
{#if noticeWords}
    <p class="notice" role="alert" data-rename-notice={notice?.kind}>
        {noticeWords.message}
        {#if noticeWords.detail}
            <!-- eslint-disable-next-line svelte/no-at-html-tags -- Markup is generated by getUserFriendlyMessage from typed error fields + tier classes; it escapes what it interpolates. -->
            <span class="notice-detail">{@html noticeWords.detail}</span>
        {/if}
    </p>
{/if}

<style>
    .check-progress,
    .unchecked {
        display: flex;
        align-items: center;
        gap: var(--spacing-sm);
    }

    .check-count {
        font-size: var(--font-size-sm);
        color: var(--color-text-secondary);
    }

    .unchecked-words {
        flex: 1;
    }

    .notice {
        margin: 0;
        padding: var(--spacing-sm);
        color: var(--color-text-secondary);
        background: var(--color-bg-tertiary);
        border-radius: var(--radius-sm);
    }

    .notice-detail {
        display: block;
        margin-top: var(--spacing-xxs);
    }
</style>
